from datetime import datetime
from typing import Any
from pydantic import BaseModel, Field


class AIInsightItem(BaseModel):
    """
    Single executive insight item generated by AI.
    """
    title: str
    description: str
    category: str = Field(..., description="Category: 'trend' | 'anomaly' | 'recommendation' | 'stat'")
    confidence: float = Field(0.95, ge=0.0, le=1.0)


class ExecutiveInsightsResponse(BaseModel):
    """
    Complete executive summary report generated for a dataset.
    """
    dataset_id: int
    dataset_name: str
    summary: str
    insights: list[AIInsightItem]
    recommended_charts: list[dict[str, Any]] = []


class AIQueryRequest(BaseModel):
    """
    Natural language question asked by user against a dataset.
    """
    dataset_id: int
    question: str = Field(..., min_length=3, max_length=500)


class ChartRecommendation(BaseModel):
    """
    Structured Recharts configuration generated by AI for dynamic visualization.
    """
    chart_type: str = Field(..., description="'bar' | 'line' | 'area' | 'pie' | 'none'")
    x_key: str
    y_key: str
    title: str
    data: list[dict[str, Any]] | None = None


class AIQueryResponse(BaseModel):
    """
    Comprehensive AI response answering user question with natural language,
    generated Pandas/Python code, and optional visual chart.
    """
    query_id: int
    question: str
    answer: str
    generated_code: str | None = None
    chart_config: ChartRecommendation | None = None
    created_at: datetime
    confidence: float = 0.95


class QueryHistoryItem(BaseModel):
    """
    Summary item of a past AI query in history.
    """
    id: int
    dataset_id: int
    question: str
    answer: str
    generated_code: str | None = None
    chart_config: dict[str, Any] | None = None
    created_at: datetime

    class Config:
        from_attributes = True
